// Offline support: the app shell is precached per build version; everything
// else (samples) is cached on first use. Stale caches are dropped on activate.
const VERSION = '__VERSION__';
const CACHE = `am-inspector-${VERSION}`;
const SHELL = [
  './',
  'index.html',
  `style.css?v=${VERSION}`,
  `pkg/automerge-inspector.js?v=${VERSION}`,
  `pkg/automerge-inspector_bg.wasm?v=${VERSION}`,
  `worker.js?v=${VERSION}`,
  'manifest.webmanifest',
  'icon.svg',
  'icon-192.png',
  'icon-512.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // the page itself is network-first, revalidating past the HTTP cache (Pages
  // serves it with max-age=600), so a new deploy shows on the next reload
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req, { cache: 'no-cache' })
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(() => caches.match(req).then((r) => r || caches.match('index.html'))),
    );
    return;
  }
  event.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    })),
  );
});
